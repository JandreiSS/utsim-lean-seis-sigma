pub fn l7() -> &'static L7Texts {
    match language() {
        Language::PtBr => &PT_BR,
        Language::En => &EN,
        Language::Es => &ES,
    }
}

/// Picks the text of the current language.
fn pick(pt: &'static str, en: &'static str, es: &'static str) -> &'static str {
    match language() {
        Language::PtBr => pt,
        Language::En => en,
        Language::Es => es,
    }
}

