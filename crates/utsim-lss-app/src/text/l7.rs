pub fn criterion_name(k: CriterionKind) -> &'static str {
    match k {
        CriterionKind::Tenure => "Tempo na empresa (meses)",
        CriterionKind::Function => "Função",
        CriterionKind::PriorLevel => "Nível anterior concluído",
        CriterionKind::ManagerRating => "Desempenho declarado pelo gestor",
        CriterionKind::HoursAvailable => "Horas disponíveis por semana",
        CriterionKind::UnitTargetOpen => "Unidade com meta aberta",
    }
}

pub fn status_name(s: NominationStatus) -> &'static str {
    match s {
        NominationStatus::Nominated => "indicado",
        NominationStatus::Selected => "selecionado",
        NominationStatus::Waiting => "lista de espera",
        NominationStatus::Refused => "não selecionado",
        NominationStatus::Withdrawn => "desistiu",
    }
}

pub fn attendance_name(a: Attendance) -> &'static str {
    match a {
        Attendance::Present => "presente",
        Attendance::Absent => "ausente",
        Attendance::Justified => "justificado",
    }
}

pub fn mode_name(m: Mode) -> &'static str {
    match m {
        Mode::App => "no app (modo prova)",
        Mode::Paper => "em papel",
    }
}

pub fn recipe_name(p: &Problem) -> &'static str {
    match p {
        Problem::Mean { .. } => "Média",
        Problem::StdDev { .. } => "Desvio-padrão",
        Problem::Cpk { .. } => "Cpk",
        Problem::Ppk { .. } => "Ppk",
        Problem::Dpmo { .. } => "DPMO",
    }
}

pub fn requirement_status_name(s: Status) -> &'static str {
    match s {
        Status::Met => "atende",
        Status::NotMet => "não atende",
        Status::Ambiguous => "ambíguo: o MBB confere",
    }
}

pub fn validity_text(v: Validity) -> String {
    match v {
        Validity::Valid => "válida".into(),
        Validity::Expiring { days } => format!("vence em {days} dias"),
        Validity::Expired => "vencida".into(),
        Validity::Revoked => "revogada".into(),
        Validity::Renewed => "renovada".into(),
    }
}
