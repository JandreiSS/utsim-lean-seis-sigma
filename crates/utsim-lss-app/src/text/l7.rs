pub fn criterion_name(k: CriterionKind) -> &'static str {
    match k {
        CriterionKind::Tenure => tx("l7-criterion_name-tenure"),
        CriterionKind::Function => tx("l7-criterion_name-function"),
        CriterionKind::PriorLevel => tx("l7-criterion_name-prior_level"),
        CriterionKind::ManagerRating => tx("l7-criterion_name-manager_rating"),
        CriterionKind::HoursAvailable => tx("l7-criterion_name-hours_available"),
        CriterionKind::UnitTargetOpen => tx("l7-criterion_name-unit_target_open"),
    }
}

pub fn status_name(s: NominationStatus) -> &'static str {
    match s {
        NominationStatus::Nominated => tx("l7-status_name-nominated"),
        NominationStatus::Selected => tx("l7-status_name-selected"),
        NominationStatus::Waiting => tx("l7-status_name-waiting"),
        NominationStatus::Refused => tx("l7-status_name-refused"),
        NominationStatus::Withdrawn => tx("l7-status_name-withdrawn"),
    }
}

pub fn attendance_name(a: Attendance) -> &'static str {
    match a {
        Attendance::Present => tx("l7-attendance_name-present"),
        Attendance::Absent => tx("l7-attendance_name-absent"),
        Attendance::Justified => tx("l7-attendance_name-justified"),
    }
}

pub fn mode_name(m: Mode) -> &'static str {
    match m {
        Mode::App => tx("l7-mode_name-app"),
        Mode::Paper => tx("l7-mode_name-paper"),
    }
}

pub fn recipe_name(p: &Problem) -> &'static str {
    match p {
        Problem::Mean { .. } => tx("l7-recipe_name-str"),
        Problem::StdDev { .. } => tx("l7-recipe_name-std_dev"),
        Problem::Cpk { .. } => "Cpk",
        Problem::Ppk { .. } => "Ppk",
        Problem::Dpmo { .. } => "DPMO",
    }
}

pub fn requirement_status_name(s: Status) -> &'static str {
    match s {
        Status::Met => tx("l7-requirement_status_name-met"),
        Status::NotMet => tx("l7-requirement_status_name-not_met"),
        Status::Ambiguous => tx("l7-requirement_status_name-ambiguous"),
    }
}

pub fn validity_text(v: Validity) -> String {
    match v {
        Validity::Valid => tx("l7-validity_text-valid").into(),
        Validity::Expiring { days } => fx("l7-validity-expiring", &[("days", days.into())]),
        Validity::Expired => tx("l7-validity_text-expired").into(),
        Validity::Revoked => tx("l7-validity_text-revoked").into(),
        Validity::Renewed => tx("l7-validity_text-renewed").into(),
    }
}
